import { writeFile } from 'node:fs/promises';
import { randomBytes } from 'node:crypto';
import mysql from 'mysql2/promise';
import { createTestDatabase } from '../test/support/mysql.js';
import { testDatabaseOptions, quoteTestSchema } from '../test/support/config.js';
import { loadMigrations, verifyStructure, historySql } from '../src/migrations.js';

// Materialise reference DDL on an isolated local test schema. Never loads .env,
// reads production data, or connects to the application database server.
const env = { ...process.env, NODE_ENV: 'test' };
let database;
try {
  const options = testDatabaseOptions(env);
  if (!['127.0.0.1','localhost','::1'].includes(options.host)) throw new Error('LOCAL_TEST_SERVER_REQUIRED');
  const plan = await loadMigrations();
  database = await createTestDatabase(env, { schema:'survey' });
  const connection = await database.connect();
  const statements = [];
  const foreignKeys = [];
  for (const table of plan.expected.tables) {
    const [[row]] = await connection.query(`SHOW CREATE TABLE \`${table.name}\``);
    const sql = row['Create Table'].replace(/ AUTO_INCREMENT=\d+/g, '');
    const lines = sql.split('\n');
    const kept = [];
    for (const line of lines) {
      if (/^\s+CONSTRAINT .* FOREIGN KEY /.test(line)) foreignKeys.push(`ALTER TABLE \`${table.name}\` ADD ${line.trim().replace(/,$/,'')};`);
      else kept.push(line);
    }
    const create = kept.join('\n').replace(/,\n\) ENGINE/, '\n) ENGINE');
    statements.push(`${create};`);
  }
  await database.closeConnection(connection);
  // Verify the standalone artifact (including its deferred cyclic FKs), not
  // merely the migration that generated it. Publish only after this passes.
  const roundtripName = `ctp_test_export_${randomBytes(8).toString('hex')}`;
  const quoted = quoteTestSchema(roundtripName);
  const roundtrip = await mysql.createConnection(options);
  let created = false;
  try {
    await roundtrip.query(`CREATE DATABASE ${quoted} CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci`);
    created = true;
    await roundtrip.query(`USE ${quoted}`);
    await roundtrip.query("SET SESSION sql_mode = 'ANSI,STRICT_ALL_TABLES,NO_ZERO_IN_DATE,NO_ZERO_DATE,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION'");
    await roundtrip.query(historySql);
    for (const sql of [...statements, ...foreignKeys]) await roundtrip.query(sql);
    await verifyStructure(roundtrip, roundtripName, plan.expected);
  } finally {
    try { if (created) await roundtrip.query(`DROP DATABASE ${quoted}`); }
    finally { await roundtrip.end(); }
  }
  const header = `-- Community tourism: survey target, ${plan.expected.tables.length} application tables, MySQL 8.4.11.
-- Reference DDL for a NEW EMPTY schema only; never import into the live Aiven schema.
-- Existing installations upgrade via backend/migrations/003_survey_schema.sql and its runner.
-- Generated by backend/scripts/export-survey-schema.js using local test MySQL, without seed.
-- Migration history is runner-owned and excluded from this reference DDL.
-- UTC timestamps; Asia/Ho_Chi_Minh business time; integer VND; no automatic cascade deletes.
SET NAMES utf8mb4 COLLATE utf8mb4_0900_ai_ci;
SET SESSION time_zone = '+00:00';
`;
  const output = new URL('../../Tai lieu he thong/Thiet ke CSDL/schema.sql', import.meta.url);
  await writeFile(output, `${header}\n${statements.join('\n\n')}\n\n${foreignKeys.join('\n')}\n`, 'utf8');
  console.log(JSON.stringify({ status:'exported', applicationTables:statements.length, foreignKeys:foreignKeys.length,
    columns:plan.expected.tables.reduce((n,t)=>n+t.columns.length,0), roundtripVerified:true, source:'isolated local MySQL', output:'Tai lieu he thong/Thiet ke CSDL/schema.sql' }));
} catch (error) {
  console.error(JSON.stringify({ code:/^[A-Z0-9_]+$/.test(error.code ?? error.message) ? (error.code ?? error.message) : 'SCHEMA_EXPORT_FAILED' }));
  process.exitCode = 1;
} finally { await database?.dispose(); }
