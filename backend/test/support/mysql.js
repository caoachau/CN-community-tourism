import mysql from 'mysql2/promise';
import { randomBytes, createHash } from 'node:crypto';
import { readdir, readFile } from 'node:fs/promises';
import { testDatabaseOptions, quoteTestSchema, HarnessError } from './config.js';
import { databaseErrorCode } from '../../src/config/database.js';
import { parseMigration } from '../../src/migrations.js';

const migrationsDirectory = new URL('../../migrations/', import.meta.url);

// This project's initial DDL has no routines, DELIMITER or semicolons in literals.
// Fail closed if a later migration uses a different SQL format or database scope.
export function migrationStatements(source) {
  const stripped = source.replace(/^\s*--[^\n]*(?:\n|$)/gm, '').trim();
  if (/\/\*|\*\/|DELIMITER|[`"#]/i.test(stripped)) throw new HarnessError('UNSUPPORTED_TEST_MIGRATION_FORMAT');
  const statements = stripped.split(';').map((sql) => sql.trim()).filter(Boolean);
  for (const sql of statements) {
    if (/^SET NAMES utf8mb4 COLLATE utf8mb4_0900_ai_ci$/i.test(sql) ||
        /^SET SESSION time_zone = '\+00:00'$/i.test(sql)) continue;
    if (!(/^CREATE TABLE [a-z][a-z0-9_]*\s*\(/i.test(sql) ||
          /^ALTER TABLE [a-z][a-z0-9_]* ADD CONSTRAINT [a-z][a-z0-9_]* FOREIGN KEY\s*\(/i.test(sql)) ||
        /\b(?:USE|DATABASE|SCHEMA|GRANT|REVOKE|DROP|TRUNCATE|RENAME|SELECT|INSERT|DELETE|UPDATE|LIKE|OUTFILE|INFILE)\b/i.test(sql) ||
        /\b(?:TABLE|REFERENCES)\s+[a-z0-9_]+\s*\./i.test(sql)) {
      throw new HarnessError('UNSAFE_TEST_MIGRATION_SCOPE');
    }
  }
  return statements;
}

export async function createTestDatabase(env = process.env, { schema = 'legacy' } = {}) {
  if (!['legacy', 'current'].includes(schema)) throw new HarnessError('INVALID_TEST_SCHEMA_VERSION');
  const options = testDatabaseOptions(env);
  const name = `ctp_test_${process.pid}_${randomBytes(8).toString('hex')}`;
  const quoted = quoteTestSchema(name);
  const token = randomBytes(32).toString('hex');
  const connections = new Set();
  let created = false;
  let marked = false;
  let control;
  try { control = await mysql.createConnection(options); }
  catch (error) { throw new HarnessError(`TEST_DATABASE_CONNECTION_FAILED_${databaseErrorCode(error)}`); }
  const schemaOptions = { ...options, database: name };

  async function connect() {
    const connection = await mysql.createConnection(schemaOptions);
    connections.add(connection);
    try {
      await connection.query("SET SESSION time_zone = '+00:00'");
      await connection.query('SET SESSION TRANSACTION ISOLATION LEVEL READ COMMITTED');
      await connection.query('SET SESSION innodb_lock_wait_timeout = 3');
      return connection;
    } catch (error) {
      await connection.end();
      connections.delete(connection);
      throw error;
    }
  }
  async function closeConnection(connection) {
    if (connections.delete(connection)) await connection.end();
  }
  async function dispose({ keep = false } = {}) {
    try {
      for (const connection of connections) {
        try { await connection.rollback(); await connection.end(); } catch { connection.destroy(); }
      }
      connections.clear();
      if (created && !keep) {
        if (marked) {
          const [[marker]] = await control.execute(`SELECT run_token FROM ${quoted}.__test_harness WHERE id = 1`);
          if (marker?.run_token !== token) throw new HarnessError('TEST_SCHEMA_OWNERSHIP_MISMATCH');
        }
        // created is set only after CREATE succeeds without IF NOT EXISTS.
        // The target was generated by this process and never supplied by a user.
        await control.query(`DROP DATABASE ${quoted}`);
        created = false;
      }
    } finally {
      await control.end();
    }
  }

  try {
    const [[server]] = await control.query('SELECT VERSION() AS version, DATABASE() AS selected_database');
    if (!/^8\.4\./.test(server.version) || server.selected_database !== options.database) {
      throw new HarnessError('MYSQL_84_TEST_SERVER_REQUIRED');
    }
    await control.query(`CREATE DATABASE ${quoted} CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci`);
    created = true;
    const connection = await connect();
    await connection.query('CREATE TABLE __test_harness (id INT PRIMARY KEY, run_token CHAR(64) NOT NULL, migration_hash CHAR(64) NULL) ENGINE=InnoDB');
    await connection.execute('INSERT INTO __test_harness (id, run_token) VALUES (1, ?)', [token]);
    marked = true;
    // Preserve the legacy fixture baseline. Auth uses the current DDL in a new,
    // empty owned schema; never concatenate a replacement after the old DDL.
    const files = (await readdir(migrationsDirectory)).filter((file) => file ===
      (schema === 'current' ? '002_compact_v3.sql' : '001_initial_schema.sql'));
    if (!files.length) throw new HarnessError('NO_TEST_MIGRATIONS_FOUND');
    const hash = createHash('sha256');
    let statementCount = 0;
    for (const file of files) {
      const source = await readFile(new URL(file, migrationsDirectory), 'utf8');
      hash.update(file).update(source);
      for (const sql of schema === 'current' ? parseMigration(source, { jsonLiterals: true }) : migrationStatements(source)) {
        try { await connection.query(sql); } catch (error) {
          // No credentials, full SQL or input row values in the surfaced error.
          throw new HarnessError(`TEST_MIGRATION_FAILED_${file}_${statementCount + 1}_${error.code ?? 'UNKNOWN'}`);
        }
        statementCount++;
      }
    }
    await connection.execute('UPDATE __test_harness SET migration_hash = ? WHERE id = 1', [hash.digest('hex')]);
    await closeConnection(connection);
    return {
      name, mysqlVersion: server.version, statementCount, connect, closeConnection, dispose,
      async rollback(work) {
        const connection = await connect();
        await connection.beginTransaction();
        try { return await work(connection); }
        finally {
          try { await connection.rollback(); }
          finally { await closeConnection(connection); }
        }
      },
    };
  } catch (error) {
    await dispose();
    throw error;
  }
}

// Independent connections and real commits are essential for lock/unique tests.
// No automatic retry: a deadlock or timeout remains visible to the calling test.
export async function concurrentTransactions(database, operations) {
  if (operations.length < 2 || operations.length > 8) throw new HarnessError('INVALID_TEST_RACE_SIZE');
  let arrived = 0;
  let release;
  let abort;
  const ready = new Promise((resolve, reject) => { release = resolve; abort = reject; });
  ready.catch(() => {}); // Also handle the case where every connection fails before arriving.
  return Promise.allSettled(operations.map(async (work) => {
    let connection;
    try {
      connection = await database.connect();
      await connection.beginTransaction();
      if (++arrived === operations.length) release();
      await ready;
      const result = await work(connection);
      await connection.commit();
      return result;
    } catch (error) {
      abort(error);
      await connection?.rollback();
      throw error;
    } finally {
      if (connection) await database.closeConnection(connection);
    }
  }));
}
